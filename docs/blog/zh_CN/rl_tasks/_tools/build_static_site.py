def _plain_text(markdown: str) -> str:
    _, body = _strip_front_matter(markdown)
    body = re.sub(r"```.*?```", " ", body, flags=re.S)
    body = re.sub(r"!\[[^\]]*]\([^)]+\)", " ", body)
    body = re.sub(r"\[([^\]]+)]\([^)]+\)", r"\1", body)
    body = re.sub(r"[#|`>*_-]+", " ", body)
    return re.sub(r"\s+", " ", body).strip()


def build_site() -> None:
    if SITE_ROOT.exists():
        shutil.rmtree(SITE_ROOT)
    SITE_ROOT.mkdir(parents=True)
    pages = collect_pages()

    images_src = DOC_ROOT / "images"
    if images_src.exists():
        shutil.copytree(images_src, SITE_ROOT / "images")

    search_index = []
    for page in pages:
        markdown = page.source.read_text(encoding="utf-8")
        html_body = markdown_to_html(markdown)
        page.output.parent.mkdir(parents=True, exist_ok=True)
        page.output.write_text(_layout(page, pages, html_body), encoding="utf-8")
        search_index.append(
            {
                "title": page.title,
                "category": page.category,
                "href": str(page.rel_output),
                "text": _plain_text(markdown)[:6000],
            }
        )

    write_assets()
    (SITE_ROOT / "search-index.json").write_text(
        json.dumps(search_index, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"built static site: {SITE_ROOT.relative_to(REPO_ROOT)}/index.html pages={len(pages)}")


