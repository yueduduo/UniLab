#!/usr/bin/env python3
"""Build a small static HTML site for the UniLab RL task blog docs.

The generator intentionally uses only the Python standard library so the docs
can be previewed without adding a blog framework dependency. It supports the
Markdown subset generated by ``generate_rl_docs.py``: front matter, headings,
paragraphs, lists, blockquotes, fenced code, tables, images, links, and inline
code.
"""

from __future__ import annotations

import html
import io
import json
